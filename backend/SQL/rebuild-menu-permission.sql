SELECT '=== 各角色菜单数量（只子菜单，父菜单按 showMenuGroup 自动显示）===' AS title;
SELECT r.role_id, r.role_name, COUNT(rm.menu_id) AS menu_count
FROM ROLE r LEFT JOIN ROLE_MENU rm ON r.role_id = rm.role_id
GROUP BY r.role_id, r.role_name ORDER BY r.role_id;

SELECT '=== 关键角色差异菜单（快速校验）===' AS title;
SELECT '预约审核(11) 应只 1/8/10/11 有，角色名单：' AS info;
SELECT r.role_name
FROM ROLE r JOIN ROLE_MENU rm ON r.role_id = rm.role_id
WHERE rm.menu_id = 11 ORDER BY r.role_id;

SELECT '发布公告(23) 不给普通教师(7)，其他全部查询角色应有，所以：' AS info;
